import axios from "axios";
import DB from "../../database";
import { v4 as uuidv4 } from "uuid";

const CreateMeeting = async (req, res) => {
  try {
    const userId = req.user.id;
    const { workspaceId, summary, description } = req.body;

    if (!workspaceId) {
      return res.status(400).json({ error: "workspaceId is required" });
    }

    const integration = await DB.integrations.findOne({ where: { userId, type: "google" } });

    if (!integration || !integration.accessToken) {
      return res.status(404).json({ error: "Google integration not connected", needsConfig: true });
    }

    const slackIntegration = await DB.integrations.findOne({ where: { userId, type: "slack" } });

    // Helper: Refresh Google token if expired
    const refreshAccessToken = async () => {
      if (!integration.refreshToken) throw new Error("No refresh token available");
      const tokenResp = await axios.post("https://oauth2.googleapis.com/token", {
        client_id: process.env.GOOGLE_CLIENT_ID,
        client_secret: process.env.GOOGLE_CLIENT_SECRET,
        refresh_token: integration.refreshToken,
        grant_type: "refresh_token",
      });
      integration.accessToken = tokenResp.data.access_token;
      await integration.save();
      return integration.accessToken;
    };

    // Helper: Make an API call with auto token refresh on 401
    const apiCall = async (method, url, data, token) => {
      const config = { headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json" } };
      try {
        return method === "post"
          ? await axios.post(url, data, config)
          : await axios.get(url, config);
      } catch (err) {
        if (err.response?.status === 401 && integration.refreshToken) {
          console.log("Google access token expired. Auto-refreshing...");
          const newToken = await refreshAccessToken();
          const retryConfig = { headers: { Authorization: `Bearer ${newToken}`, "Content-Type": "application/json" } };
          return method === "post"
            ? await axios.post(url, data, retryConfig)
            : await axios.get(url, retryConfig);
        }
        throw err;
      }
    };

    let currentAccessToken = integration.accessToken;

    // Step 1: Create a Meet Space via the Google Meet REST API
    // This gives us the proper internal space name (e.g. "spaces/abc123XYZ")
    // which is required by the Workspace Events API
    let spaceResp;
    try {
      spaceResp = await apiCall("post", "https://meet.googleapis.com/v2/spaces", {}, currentAccessToken);
      currentAccessToken = integration.accessToken; // may have been refreshed
    } catch (spaceErr) {
      console.error("Failed to create Meet space:", spaceErr.response?.data || spaceErr.message);
      return res.status(500).json({ error: "Failed to create Meet space" });
    }

    const spaceName = spaceResp.data.name;           // "spaces/INTERNAL_ID"
    const meetingUri = spaceResp.data.meetingUri;     // "https://meet.google.com/xxx-yyyy-zzz"
    const meetingCode = spaceResp.data.meetingCode;   // "xxx-yyyy-zzz"
    const spaceId = spaceName.split("spaces/")[1];    // "INTERNAL_ID"

    console.log(`Meet Space created: ${spaceName} | URI: ${meetingUri} | Code: ${meetingCode}`);

    // Step 2: Create Google Calendar Event with the existing Meet space link
    const requestBody = {
      summary: summary || "KORE Sync Meeting",
      description: description || "Meeting generated by KORE Bot",
      start: { dateTime: new Date().toISOString() },
      end: { dateTime: new Date(Date.now() + 30 * 60000).toISOString() },
      conferenceData: {
        entryPoints: [{
          entryPointType: "video",
          uri: meetingUri,
          label: meetingCode
        }],
        conferenceSolution: {
          key: { type: "hangoutsMeet" }
        },
        conferenceId: meetingCode
      },
    };

    let calendarResp;
    try {
      calendarResp = await apiCall(
        "post",
        "https://www.googleapis.com/calendar/v3/calendars/primary/events?conferenceDataVersion=1",
        requestBody,
        currentAccessToken
      );
      currentAccessToken = integration.accessToken;
    } catch (calErr) {
      console.error("Calendar event creation failed:", calErr.response?.data || calErr.message);
      return res.status(500).json({ error: "Failed to create calendar event" });
    }

    const meetingUrl = calendarResp.data.hangoutLink || meetingUri;
    const calendarEventId = calendarResp.data.id;

    console.log(`Calendar event created: ${calendarEventId} | Meet URL: ${meetingUrl}`);

    // Step 3: Create Workspace Events Subscription for this meeting space
    let subscriptionId = null;
    if (process.env.GOOGLE_PUBSUB_TOPIC) {
      try {
        const subscriptionBody = {
          targetResource: `//meet.googleapis.com/${spaceName}`,
          eventTypes: [
            "google.workspace.meet.conference.v2.started",
            "google.workspace.meet.conference.v2.ended",
            "google.workspace.meet.participant.v2.joined",
            "google.workspace.meet.participant.v2.left"
          ],
          notificationEndpoint: {
            pubsubTopic: process.env.GOOGLE_PUBSUB_TOPIC
          },
          payloadOptions: {
            includeResource: false
          }
        };

        const subResp = await apiCall(
          "post",
          "https://workspaceevents.googleapis.com/v1/subscriptions",
          subscriptionBody,
          currentAccessToken
        );

        subscriptionId = subResp.data.name || subResp.data.metadata?.subscription || null;
        console.log(`Workspace Events Subscription created: ${subscriptionId}`);
      } catch (subErr) {
        // Non-fatal: meeting still works, just won't get live events
        console.error("Failed to create Workspace Events subscription:", subErr.response?.data || subErr.message);
      }
    } else {
      console.log("Skipping Workspace Events subscription: GOOGLE_PUBSUB_TOPIC not configured");
    }

    // Step 4: Persist meeting record
    const meeting = await DB.meetings.create({
      workspaceId,
      userId,
      summary: summary || "KORE Sync Meeting",
      meetingUrl,
      calendarEventId,
      spaceId,
      subscriptionId,
      status: "scheduled"
    });

    // Step 5: Notify Slack (if connected)
    if (slackIntegration && slackIntegration.accessToken) {
      const wsRepo = await DB.workspaceRepos.findOne({ 
        where: { workspaceId },
        include: [{ model: DB.slackChannels, as: "slackChannel" }]
      });

      if (wsRepo?.slackChannel?.channelId) {
        try {
          await axios.post("https://slack.com/api/chat.postMessage", {
            channel: wsRepo.slackChannel.channelId,
            text: `🚀 *New Meeting Started*: ${summary || 'KORE Sync'}\n🔗 *Join here*: ${meetingUrl}\n_KORE Bot will be monitoring the health of this meeting._`
          }, {
            headers: { Authorization: `Bearer ${slackIntegration.accessToken}` }
          });
        } catch (e) {
          console.error("Failed to notify Slack:", e.message);
        }
      }
    }

    return res.status(200).json({ 
      success: true, 
      meetingUrl, 
      eventId: calendarEventId,
      meetingId: meeting.id,
      spaceId,
      subscriptionActive: !!subscriptionId
    });

  } catch (err) {
    console.error("Create Meeting Error:", err.response?.data || err.message);
    if (err.response?.status === 401) {
      return res.status(401).json({ error: "Google session expired. Please reconnect.", needsRefresh: true });
    }
    return res.status(500).json({ error: "Failed to create meeting" });
  }
};

export default CreateMeeting;
